SELECT
    B.PRICE_GROUP AS PRICE_GROUP,
    COUNT(*) AS PRODUCTS
FROM (
    SELECT
        *,
        CASE 
            WHEN TEMP = 0 THEN 0
            ELSE TEMP * 10000
        END AS PRICE_GROUP
    FROM (
        SELECT
            *,
            FLOOR(PRICE / 10000) AS TEMP
        FROM PRODUCT
    ) AS A
) AS B
GROUP BY B.PRICE_GROUP
ORDER BY B.PRICE_GROUP ASC;