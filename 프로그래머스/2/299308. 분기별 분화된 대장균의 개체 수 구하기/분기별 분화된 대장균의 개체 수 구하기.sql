SELECT
    CONCAT(ED.QUARTER, 'Q') AS QUARTER,
    COUNT(*) AS ECOLI_COUNT
FROM (
    SELECT
        *,
        CASE
            WHEN MONTH(DIFFERENTIATION_DATE) BETWEEN '01' AND '03' THEN 1
            WHEN MONTH(DIFFERENTIATION_DATE) BETWEEN '04' AND '06' THEN 2
            WHEN MONTH(DIFFERENTIATION_DATE) BETWEEN '07' AND '09' THEN 3
            ELSE 4
        END AS QUARTER
    FROM ECOLI_DATA
) AS ED
GROUP BY ED.QUARTER
ORDER BY ED.QUARTER ;