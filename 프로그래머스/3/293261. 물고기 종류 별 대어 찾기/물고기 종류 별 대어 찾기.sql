SELECT
    FI.ID,
    FNI.FISH_NAME,
    FI.LENGTH
FROM (
    SELECT
        ID,
        FISH_TYPE,
        LENGTH,
        ROW_NUMBER() OVER (PARTITION BY FISH_TYPE ORDER BY LENGTH DESC) AS RANKING
    FROM FISH_INFO
) AS FI
JOIN FISH_NAME_INFO FNI
ON FI.FISH_TYPE = FNI.FISH_TYPE
WHERE FI.RANKING = 1
ORDER BY 1;