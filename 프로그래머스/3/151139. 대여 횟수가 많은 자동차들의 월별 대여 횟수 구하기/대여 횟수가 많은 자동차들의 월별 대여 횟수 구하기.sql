SELECT
    MONTH(CRCRH.START_DATE) AS MONTH, 
    CRCRH.CAR_ID AS CAR_ID,
    COUNT(*) AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY CRCRH
WHERE CRCRH.START_DATE >= '2022-08-01' AND CRCRH.START_DATE <= '2022-10-31' AND CRCRH.CAR_ID IN (
    SELECT
        CAR_ID
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY C
    WHERE C.START_DATE >= '2022-08-01' AND C.START_DATE <= '2022-10-31'
    GROUP BY CAR_ID
    HAVING COUNT(*) >= 5   
)
GROUP BY MONTH(CRCRH.START_DATE), CRCRH.CAR_ID
ORDER BY MONTH(CRCRH.START_DATE), CRCRH.CAR_ID DESC